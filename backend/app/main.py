"""Cognexa — FastAPI application entrypoint.

Run locally:

    cd backend
    python -m uvicorn app.main:app --reload --port 8000

This server makes NO AI calls in the current phase.  It serves structured mock
study material behind a stable API contract that the future Gemma 4 generator
(`app/services/gemma4.py`) will plug into.
"""

from __future__ import annotations

import logging
from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from .config import get_settings
from .errors import register_exception_handlers
from .routes import generate, health, uploads
from .storage import ensure_upload_dir

logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
logger = logging.getLogger("mindmap_ai")


@asynccontextmanager
async def lifespan(app: FastAPI):
    settings = get_settings()
    ensure_upload_dir(settings.upload_path)
    logger.info(
        "Cognexa backend up — AI_PROVIDER=%s (ai_configured=%s), model=%s, upload limit=%dMB",
        settings.ai_provider,
        settings.ai_configured,
        settings.gemma_model,
        settings.max_upload_mb,
    )
    if settings.ai_provider == "gemma4" and not settings.google_api_key:
        logger.warning(
            "AI_PROVIDER=gemma4 but GOOGLE_API_KEY is missing; generate requests will fail with 503."
        )
    elif settings.ai_provider == "mock":
        logger.info("Mock generator active — no AI calls will be made.")
    yield


def create_app() -> FastAPI:
    settings = get_settings()

    app = FastAPI(
        title="Cognexa API",
        version="0.1.0",
        description=(
            "Cognexa — understand the connections. Turn textbook pages into visual mind maps. "
            "Study material is generated by "
            "Gemma 4 (gemma-4-31b-it) via Google AI Studio; an offline mock provider is "
            "available for demos, and its results are clearly labelled."
        ),
        lifespan=lifespan,
    )

    app.add_middleware(
        CORSMiddleware,
        allow_origins=settings.cors_origin_list,
        allow_credentials=False,
        allow_methods=["GET", "POST", "OPTIONS"],
        allow_headers=["*"],
    )

    register_exception_handlers(app)

    app.include_router(health.router)
    app.include_router(uploads.router)
    app.include_router(generate.router)

    return app


app = create_app()
